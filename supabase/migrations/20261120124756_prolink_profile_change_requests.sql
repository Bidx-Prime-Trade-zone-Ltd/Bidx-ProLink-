-- Private ProLink professional profile change requests.
-- All access is mediated by the authenticated ProLink Worker using service_role.
create table if not exists public.prolink_profile_change_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  requested_changes jsonb not null default '{}'::jsonb
    check (jsonb_typeof(requested_changes) = 'object' and requested_changes <> '{}'::jsonb),
  status text not null default 'pending'
    check (status in ('pending','approved','rejected')),
  requested_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null,
  review_reason text,
  approved_at timestamptz
);

create index if not exists prolink_profile_change_requests_status_requested_idx
  on public.prolink_profile_change_requests(status, requested_at desc);
create index if not exists prolink_profile_change_requests_user_requested_idx
  on public.prolink_profile_change_requests(user_id, requested_at desc);

alter table public.prolink_profile_change_requests enable row level security;
revoke all on public.prolink_profile_change_requests from anon, authenticated;
grant all on public.prolink_profile_change_requests to service_role;
grant usage, select on sequence public.prolink_profile_change_requests_id_seq to service_role;

comment on table public.prolink_profile_change_requests is
  'Private ProLink professional profile change requests. All reads and writes are mediated by the authenticated ProLink Worker; browser roles have no direct table access.';
